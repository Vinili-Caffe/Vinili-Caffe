const { ADMIN_EN, ADMIN_IT } = require("./adminPacks");
const { TENANT_LANGUAGES } = require("./languages");
const { ADMIN_LOCALE_OVERRIDES } = require("./adminLocaleOverrides");

const VERIFIED_ADMIN_LOCALES = {
  sv: ADMIN_UI_LOCALES.sv,
  es: ADMIN_UI_LOCALES.es,
};

function applyAdminUiPacks(uiPacks) {
  for (const code of TENANT_LANGUAGES) {
    if (!uiPacks[code]) continue;
    const baseAdmin = ADMIN_IT;
    const verified = VERIFIED_ADMIN_LOCALES[code];
    const override = ADMIN_LOCALE_OVERRIDES[code];
    uiPacks[code] = {
      ...uiPacks[code],
      ...baseAdmin,
      ...(code === "it" ? {} : verified || {}),
      ...(override || {}),
    };
  }
}

module.exports = { ADMIN_UI_LOCALES, applyAdminUiPacks };
