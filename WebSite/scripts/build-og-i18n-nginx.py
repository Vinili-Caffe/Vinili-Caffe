#!/usr/bin/env python3
"""Generate nginx map+sub_filter for EN Open Graph / meta from og-meta.json."""
from __future__ import annotations
import json
import re
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
META = ROOT / "js/i18n/og-meta.json"
OUT = ROOT / "deploy/nginx-og-i18n-en.conf"


def amp_variants(s: str) -> list[str]:
    s = str(s or "")
    out = {s, s.replace("&", "&amp;")}
    return list(out)


def slug(s: str) -> str:
    s = re.sub(r"[^a-zA-Z0-9]+", "_", s).strip("_").lower()
    return (s[:48] or "x")


def main() -> None:
    data = json.loads(META.read_text(encoding="utf-8"))
    maps: list[str] = []
    filters: list[str] = []
    used = set()
    idx = 0

    # locale
    maps.append("map $vc_og_en $vc_og_locale {")
    maps.append('    default "it_IT";')
    maps.append('    1 "en_US";')
    maps.append("}")
    filters.append(
        "sub_filter 'property=\"og:locale\" content=\"it_IT\"' "
        "'property=\"og:locale\" content=\"$vc_og_locale\"';"
    )

    # Frasi condivise (titoli home con conteggio membri dinamico, ecc.)
    extras = [
        (
            "Community Discord italiana",
            "Italian Discord community",
        ),
        (
            "Entra nel server ufficiale Vinili & Caffè.",
            "Join the official Vinili & Caffè server.",
        ),
        (
            "Entra nel server ufficiale Vinili &amp; Caffè.",
            "Join the official Vinili &amp; Caffè server.",
        ),
        (
            "Domande frequenti su Vinili &amp; Caffè.",
            "Frequently asked questions about Vinili &amp; Caffè.",
        ),
        (
            "Domande frequenti su Vinili & Caffè.",
            "Frequently asked questions about Vinili & Caffè.",
        ),
        # title fragments (HTML short <title> without brand suffix)
        ("Bacheca · Server", "Board · Servers"),
        ("Bacheca · Bot", "Board · Bots"),
        ("Bacheca · Scheda", "Board · Listing"),
        ("Bacheca · Invia", "Board · Submit"),
        ("Bacheca · Le mie schede", "Board · My listings"),
        ("Bacheca · Moderazione", "Board · Moderation"),
        ("Bacheca · Vota", "Board · Vote"),
        ("Bacheca · Pubblica", "Board · Publish"),
        ("Serata Film", "Movie Night"),
        ("Serata film", "Movie night"),
        ("Puzzle (prova)", "Puzzle (beta)"),
        ("Coda moderazione Bacheca.", "Board moderation queue."),
        ("Server Discord in Bacheca — Vinili & Caffè.", "Discord servers on the Board — Vinili & Caffè."),
        ("Bot Discord in Bacheca — Vinili & Caffè.", "Discord bots on the Board — Vinili & Caffè."),
        ("Gestisci le tue schede in Bacheca.", "Manage your Board listings."),
        ("Vota una scheda in Bacheca — Vinili & Caffè.", "Vote for a Board listing — Vinili & Caffè."),
        ("Pubblica un server o un bot in Bacheca.", "Publish a server or bot on the Board."),
        ("Scheda in Bacheca — Vinili & Caffè.", "Board listing — Vinili & Caffè."),
    ]

    def add_pair(itv: str, env: str, tag: str) -> None:
        nonlocal idx
        itv = str(itv or "").strip()
        env = str(env or "").strip()
        if not itv or not env or itv == env:
            return
        for it_var in amp_variants(itv):
            # skip double-amp on already-amped
            idx += 1
            var = f"vc_og_{slug(tag)}_{idx}"
            if var in used:
                continue
            used.add(var)
            it_esc = it_var.replace("\\", "\\\\").replace('"', '\\"')
            en_esc = env.replace("\\", "\\\\").replace('"', '\\"')
            # prefer matching amp form for EN when IT has amp
            if "&amp;" in it_var and "&amp;" not in en_esc and "&" in env:
                en_esc = env.replace("&", "&amp;").replace("\\", "\\\\").replace('"', '\\"')
            maps.append(f"map $vc_og_en ${var} {{")
            maps.append(f'    default "{it_esc}";')
            maps.append(f'    1 "{en_esc}";')
            maps.append("}")
            filters.append(f"sub_filter '{it_var}' '${var}';")

    for route, langs in data.items():
        it = langs.get("it") or {}
        en = langs.get("en") or {}
        for field in ("title", "description"):
            add_pair(it.get(field), en.get(field), f"{route}_{field}")

    for a, b in extras:
        add_pair(a, b, "extra")

    lines = [
        "# AUTO-GENERATED by scripts/build-og-i18n-nginx.py — do not edit",
        "# Requires: set $vc_lang_cookie \"\"; at server level",
        "#           map for $vc_og_en (see nginx-og-i18n-map.conf)",
        "",
    ]
    # Split: maps go in http{} or server{}; filters in location
    map_out = ROOT / "deploy/nginx-og-i18n-maps.conf"
    filt_out = ROOT / "deploy/nginx-og-i18n-filters.conf"

    map_header = [
        "# AUTO-GENERATED maps for EN Open Graph",
        "map \"$vc_lang_cookie:$cookie_vc_site_lang\" $vc_og_en {",
        '    default 0;',
        '    "~*^en:" 1;',
        '    "~:en$" 1;',
        '    "~*^en:en" 1;',
        "}",
        "",
    ]
    map_out.write_text("\n".join(map_header + maps) + "\n", encoding="utf-8")

    filt_body = [
        "# AUTO-GENERATED sub_filter for EN Open Graph (Discord/FB crawlers)",
        "# (sub_filter_types / sub_filter_once li imposta il location host)",
        "",
        *filters,
        "",
    ]
    filt_out.write_text("\n".join(filt_body), encoding="utf-8")
    print("OK", map_out, "vars", len(used))
    print("OK", filt_out, "filters", len(filters))


if __name__ == "__main__":
    main()
