#!/usr/bin/env node
/**
 * Genera snippet nginx sub_filter per og:title/description EN
 * da js/i18n/og-meta.json (Discord/FB crawler — niente JS).
 */
const fs = require("fs");
const path = require("path");

const ROOT = path.resolve(__dirname, "..");
const META = path.join(ROOT, "js/i18n/og-meta.json");
const OUT = path.join(ROOT, "deploy/nginx-og-i18n-en.conf");

function escNginx(s) {
  return String(s || "")
    .replace(/\\/g, "\\\\")
    .replace(/'/g, "\\'")
    .replace(/&/g, "&amp;");
}

function variants(raw) {
  const s = String(raw || "");
  const amp = s.replace(/&/g, "&amp;");
  const set = new Set([s, amp]);
  return [...set];
}

function main() {
  const data = JSON.parse(fs.readFileSync(META, "utf8"));
  const lines = [];
  lines.push("# AUTO-GENERATED by scripts/build-og-i18n-nginx.cjs — do not edit by hand");
  lines.push("# Apply when $vc_og_lang = en (cookie o prefisso /en/)");
  lines.push("# Include inside server { } that serves HTML (www).");
  lines.push("");
  lines.push("sub_filter_types text/html;");
  lines.push("sub_filter_once off;");
  lines.push("");

  const pairs = [];
  pairs.push(["it_IT", "en_US"]); // og:locale

  for (const [route, langs] of Object.entries(data)) {
    const it = langs.it || {};
    const en = langs.en || {};
    if (it.title && en.title && it.title !== en.title) {
      for (const a of variants(it.title)) {
        for (const b of variants(en.title)) {
          pairs.push([a, b]);
        }
      }
    }
    if (it.description && en.description && it.description !== en.description) {
      for (const a of variants(it.description)) {
        for (const b of variants(en.description)) {
          pairs.push([a, b]);
        }
      }
    }
  }

  // dedupe by from
  const seen = new Set();
  for (const [from, to] of pairs) {
    const key = from + "\0" + to;
    if (seen.has(key) || from === to) continue;
    seen.add(key);
    lines.push(`sub_filter '${escNginx(from)}' '${escNginx(to)}';`);
  }

  lines.push("");
  fs.writeFileSync(OUT, lines.join("\n") + "\n", "utf8");
  console.log("Wrote", OUT, "filters", seen.size);
}

main();
